/**
 * Определение категории косметологии по названию услуги
 */
export function getCosmetologyCategory(serviceName: string, groupName?: string): CosmetologyCategory | null {
  const text = `${serviceName} ${groupName || ''}`.toLowerCase();

  // Явно исключаем услуги других медицинских специальностей
  if (NON_COSMETOLOGY_KEYWORDS.some(keyword => text.includes(keyword))) {
    return null;
  }

  for (const category of COSMETOLOGY_CATEGORIES) {
    if (category.keywords.some(keyword => text.includes(keyword))) {
      return category;
    }
  }

  return null;
}

/**
 * Получение категории по slug
 */
export function getCategoryBySlug(slug: string): CosmetologyCategory | null {
  return COSMETOLOGY_CATEGORIES.find(c => c.slug === slug) || null;
}

/**
 * Получение всех категорий
 */
export function getAllCategories(): CosmetologyCategory[] {
  return [...COSMETOLOGY_CATEGORIES].sort((a, b) => a.order - b.order);
}

