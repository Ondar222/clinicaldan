/**
 * Metadata для страницы.
 * @param path      канонический путь (используется для canonical)
 * @param seoPath   ключ в SEO_PAGES; по умолчанию = path.
 *                  Для динамических маршрутов передаётся путь раздела,
 *                  как это делал прежний SSR (prefix-match).
 */
export function pageMeta(path: string, seoPath?: string): Metadata {
  const seo = SEO_PAGES[seoPath ?? path] ?? SEO_PAGES['/'];
  const noindex =
    seo.noindex || path.startsWith('/staff') || path.startsWith('/payment');

  return {
    title: { absolute: seo.title },
    description: seo.description,
    alternates: { canonical: path },
    ...(noindex
      ? { robots: { index: false, follow: false } }
      : {}),
    openGraph: {
      title: seo.title,
      description: seo.description,
      url: path,
      type: 'website',
    },
    twitter: {
      title: seo.title,
      description: seo.description,
    },
  };
}
